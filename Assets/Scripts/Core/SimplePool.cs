using UnityEngine;
using System.Collections.Generic;

public static class SimplePool<T> where T : Component
{
    private static readonly Dictionary<T, Queue<T>> _pools = new Dictionary<T, Queue<T>>();
    private static Transform _poolRoot;

    public static T Spawn(T prefab, Vector3 position, Quaternion rotation)
    {
        if (prefab == null) return null;

        if (_poolRoot == null)
        {
            GameObject rootObj = GameObject.Find("[PoolRoot]");
            if (rootObj == null)
            {
                rootObj = new GameObject("[PoolRoot]");
                Object.DontDestroyOnLoad(rootObj);
            }
            _poolRoot = rootObj.transform;
        }

        if (!_pools.TryGetValue(prefab, out var queue))
        {
            queue = new Queue<T>();
            _pools[prefab] = queue;
        }

        T obj;
        if (queue.Count > 0)
        {
            obj = queue.Dequeue();
            obj.transform.SetPositionAndRotation(position, rotation);
            obj.gameObject.SetActive(true);
        }
        else
        {
            obj = Object.Instantiate(prefab, position, rotation, _poolRoot);
            obj.gameObject.SetActive(true);
        }

        return obj;
    }

